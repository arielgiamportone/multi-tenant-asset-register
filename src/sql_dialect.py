"""Run one raw-SQL codebase on SQLite and PostgreSQL.

The application was written against SQLite: `?` placeholders, `INSERT OR IGNORE`,
`datetime('now')`, `AUTOINCREMENT`. Rewriting hundreds of call sites for a second
engine was not an option, so every statement goes through `to_postgres()` when the
active engine is PostgreSQL. Each tenant lives in its own schema, selected with a
validated `SET search_path`.

Only the SQLite-isms the codebase actually uses are translated. Anything else is
left alone on purpose: a translator that guesses is worse than one that fails loudly.
"""
from __future__ import annotations

import re
from typing import Iterator, Mapping, Sequence

# ---------------------------------------------------------------- tokenizer


def split_literals(sql: str) -> Iterator[tuple[bool, str]]:
    """Yield (is_literal, chunk). Literals are '...' strings and "..." identifiers.

    Rewrites only touch code chunks, so a `?` or `datetime('now')` inside a
    string literal survives untouched. Doubled quotes ('it''s') stay inside
    the literal because the scanner simply re-enters it.
    """
    i, n, start = 0, len(sql), 0
    while i < n:
        ch = sql[i]
        if ch in ("'", '"'):
            if i > start:
                yield False, sql[start:i]
            j = i + 1
            while j < n:
                if sql[j] == ch:
                    if j + 1 < n and sql[j + 1] == ch:  # escaped quote
                        j += 2
                        continue
                    break
                j += 1
            yield True, sql[i:j + 1]
            i = start = j + 1
        else:
            i += 1
    if start < n:
        yield False, sql[start:]


def _map_code(sql: str, fn) -> str:
    return "".join(chunk if lit else fn(chunk) for lit, chunk in split_literals(sql))


# ---------------------------------------------------------------- rewrites

_AUTOINC = re.compile(r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b", re.I)
_ADD_COLUMN = re.compile(r"\bADD\s+COLUMN\s+(?!IF\s+NOT\s+EXISTS\b)", re.I)
_BLOB = re.compile(r"\bBLOB\b", re.I)
_INSERT_OR = re.compile(
    r"^\s*INSERT\s+OR\s+(IGNORE|REPLACE)\s+INTO\s+(\w+)\s*\(([^)]*)\)", re.I
)
_UTC = "(now() AT TIME ZONE 'UTC')"


def _rewrite_ddl(code: str) -> str:
    code = _AUTOINC.sub("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", code)
    code = _ADD_COLUMN.sub("ADD COLUMN IF NOT EXISTS ", code)
    return _BLOB.sub("BYTEA", code)


def _rewrite_dates(sql: str) -> str:
    # These span a literal ('now'), so they run on the whole statement. The
    # patterns are anchored on the function name, which never appears in data.
    sql = re.sub(
        r"date\(\s*'now'\s*,\s*'([+-]?\d+) days?'\s*\)",
        rf"to_char({_UTC}::date + INTERVAL '\1 days', 'YYYY-MM-DD')",
        sql, flags=re.I,
    )
    sql = re.sub(r"datetime\(\s*'now'\s*\)",
                 f"to_char({_UTC}, 'YYYY-MM-DD HH24:MI:SS')", sql, flags=re.I)
    return re.sub(r"date\(\s*'now'\s*\)",
                  f"to_char({_UTC}::date, 'YYYY-MM-DD')", sql, flags=re.I)


def _rewrite_insert_or(sql: str, conflict_keys: Mapping[str, Sequence[str]]) -> str:
    m = _INSERT_OR.match(sql)
    if not m:
        return sql
    mode, table, cols = m.group(1).upper(), m.group(2), m.group(3)
    head = f"INSERT INTO {table} ({cols})"
    body = sql[m.end():].rstrip().rstrip(";")
    if mode == "IGNORE":
        return f"{head}{body} ON CONFLICT DO NOTHING"
    # OR REPLACE needs an explicit conflict target in PostgreSQL. SQLite infers
    # it from any unique index; we refuse to guess.
    keys = conflict_keys.get(table)
    if not keys:
        raise ValueError(f"INSERT OR REPLACE on {table!r}: declare its conflict key")
    columns = [c.strip() for c in cols.split(",")]
    updates = ", ".join(f"{c} = EXCLUDED.{c}" for c in columns if c not in keys)
    action = f"DO UPDATE SET {updates}" if updates else "DO NOTHING"
    return f"{head}{body} ON CONFLICT ({', '.join(keys)}) {action}"


def _rewrite_params(code: str) -> str:
    # psycopg %-formats the statement when parameters are passed, so a literal
    # `%` in code (modulo operator) must be doubled. Inside string literals
    # too: LIKE '%x%' is also %-formatted. Handled in to_postgres().
    return code.replace("%", "%%").replace("?", "%s")


def to_postgres(sql: str, has_params: bool,
                conflict_keys: Mapping[str, Sequence[str]] | None = None) -> str:
    """Translate one SQLite statement to PostgreSQL.

    `has_params` matters: psycopg only applies %-formatting when parameters are
    given, so `%` must be escaped then and *only* then (see lesson 02).
    """
    sql = _rewrite_insert_or(sql, conflict_keys or {})
    sql = _rewrite_dates(sql)
    if re.match(r"\s*(CREATE|ALTER)\b", sql, re.I):
        sql = _map_code(sql, _rewrite_ddl)
    if has_params:
        sql = "".join(
            chunk.replace("%", "%%") if lit else _rewrite_params(chunk)
            for lit, chunk in split_literals(sql)
        )
    return sql


# ---------------------------------------------------------------- tenants

_TENANT = re.compile(r"^[a-z][a-z0-9_]{1,40}$")


def resolve_tenant(raw: str, aliases: Mapping[str, str], known: set[str]) -> str:
    """Normalise a tenant id that came from outside (URL, cookie, token, CLI).

    The same id builds a schema name and file paths, so it is checked against a
    strict pattern *and* the list of provisioned tenants before anything uses it.
    """
    key = raw.strip().lower()
    tenant = aliases.get(key, key)
    if not _TENANT.fullmatch(tenant) or tenant not in known:
        raise PermissionError(f"unknown tenant: {raw!r}")
    return tenant


def search_path_sql(tenant: str) -> str:
    """`SET search_path` for an already-resolved tenant. Identifiers cannot be
    bound as parameters, hence the re-check here instead of trusting callers."""
    if not _TENANT.fullmatch(tenant):
        raise PermissionError(f"invalid schema name: {tenant!r}")
    return f'SET search_path TO "t_{tenant}", public'
