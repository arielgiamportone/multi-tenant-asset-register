class Literals(unittest.TestCase):
    def test_doubled_quote_stays_inside_literal(self):
        parts = list(split_literals("SELECT 'it''s ?' , ?"))
        self.assertEqual(parts, [(False, "SELECT "), (True, "'it''s ?'"), (False, " , ?")])


class Placeholders(unittest.TestCase):
    def test_question_mark_in_literal_is_data(self):
        self.assertEqual(to_postgres("SELECT * FROM t WHERE a = ? AND b = '?'", True),
                         "SELECT * FROM t WHERE a = %s AND b = '?'")

    def test_percent_escaped_everywhere_when_params_are_passed(self):
        self.assertEqual(to_postgres("SELECT id % 2 FROM t WHERE n LIKE '%park%' AND id = ?", True),
                         "SELECT id %% 2 FROM t WHERE n LIKE '%%park%%' AND id = %s")

    def test_percent_untouched_without_params(self):
        sql = "SELECT * FROM t WHERE n LIKE '%park%'"
        self.assertEqual(to_postgres(sql, False), sql)


class Upserts(unittest.TestCase):
    def test_insert_or_ignore(self):
        self.assertEqual(to_postgres("INSERT OR IGNORE INTO tags (code, asset) VALUES (?, ?)", True),
                         "INSERT INTO tags (code, asset) VALUES (%s, %s) ON CONFLICT DO NOTHING")

    def test_insert_or_replace_with_declared_key(self):
        out = to_postgres("INSERT OR REPLACE INTO settings (key, value) VALUES (?, ?)", True,
                          conflict_keys={"settings": ("key",)})
        self.assertEqual(out, "INSERT INTO settings (key, value) VALUES (%s, %s) "
                              "ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value")

    def test_insert_or_replace_without_key_refuses_to_guess(self):
        with self.assertRaises(ValueError):
            to_postgres("INSERT OR REPLACE INTO settings (key, value) VALUES (?, ?)", True)


class DatesAndDdl(unittest.TestCase):
    def test_now_functions(self):
        out = to_postgres("UPDATE t SET seen = datetime('now') WHERE d < date('now', '-30 days')", False)
        self.assertNotIn("datetime(", out)
        self.assertIn("INTERVAL '-30 days'", out)
        self.assertIn("'YYYY-MM-DD HH24:MI:SS'", out)

    def test_ddl(self):
        out = to_postgres("CREATE TABLE a (id INTEGER PRIMARY KEY AUTOINCREMENT, img BLOB)", False)
        self.assertEqual(out, "CREATE TABLE a (id BIGINT GENERATED BY DEFAULT AS IDENTITY "
                              "PRIMARY KEY, img BYTEA)")

    def test_add_column_becomes_idempotent(self):
        self.assertEqual(to_postgres("ALTER TABLE a ADD COLUMN note TEXT", False),
                         "ALTER TABLE a ADD COLUMN IF NOT EXISTS note TEXT")


class SourceDialectIsReal(unittest.TestCase):
    """The SQLite inputs used above really run on SQLite."""

    def test_inputs_execute_on_sqlite(self):
        db = sqlite3.connect(":memory:")
        db.execute("CREATE TABLE a (id INTEGER PRIMARY KEY AUTOINCREMENT, img BLOB)")
        db.execute("ALTER TABLE a ADD COLUMN note TEXT")
        db.execute("CREATE TABLE tags (code TEXT PRIMARY KEY, asset TEXT)")
        for _ in range(2):
            db.execute("INSERT OR IGNORE INTO tags (code, asset) VALUES (?, ?)", ("X1", "B-1"))
        self.assertEqual(db.execute("SELECT count(*) FROM tags").fetchone()[0], 1)
        db.execute("SELECT date('now', '-30 days'), datetime('now')")


class Tenants(unittest.TestCase):
    KNOWN = {"northvale", "demo_town"}
    ALIASES = {"nv": "northvale"}

    def test_alias_and_case(self):
        self.assertEqual(resolve_tenant(" NV ", self.ALIASES, self.KNOWN), "northvale")

    def test_rejects_traversal_and_unknown(self):
        for raw in ("../northvale", "northvale;drop", "other_town", ""):
            with self.assertRaises(PermissionError):
                resolve_tenant(raw, self.ALIASES, self.KNOWN)

    def test_search_path(self):
        self.assertEqual(search_path_sql("northvale"), 'SET search_path TO "t_northvale", public')
        with self.assertRaises(PermissionError):
            search_path_sql('x"; DROP SCHEMA public; --')


